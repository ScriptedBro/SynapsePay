import { describe, it, expect, vi } from 'vitest';
import { buildApp } from '../../src/api/app.js';
import { ContractManager } from '../../src/core/contract-manager.js';
import { SynapseArbitrator } from '../../src/arbitration/arbitrator.js';
import { PayPalOrdersManager } from '../../src/paypal/orders.js';
import { PayPalPayoutsManager } from '../../src/paypal/payouts.js';
import { PayPalWebhookGuard } from '../../src/paypal/webhook-guard.js';
import { PayPalClient } from '../../src/paypal/client.js';
import { loadConfig } from '../../src/config.js';

describe('API Integration via Fastify Inject', () => {
  const config = loadConfig({
    API_KEY: 'test_sec_api_key_valid_123',
    NODE_ENV: 'test',
  });

  const mockClient = new PayPalClient({
    clientId: 'mock_client',
    clientSecret: 'mock_secret',
    mode: 'sandbox',
  });

  const ordersManager = new PayPalOrdersManager(mockClient);
  const payoutsManager = new PayPalPayoutsManager(mockClient);
  const webhookGuard = new PayPalWebhookGuard(mockClient);
  const arbitrator = new SynapseArbitrator(config.AUDIT_HMAC_SECRET);

  vi.spyOn(ordersManager, 'createAuthorizationOrder').mockResolvedValue({
    orderId: 'ORD_API_MOCK_123',
    status: 'CREATED',
    approvalUrl: 'https://sandbox.paypal.com/checkoutnow?token=ORD_API_MOCK_123',
  });

  vi.spyOn(ordersManager, 'captureAuthorization').mockResolvedValue({
    captureId: 'CAP_API_456',
    status: 'COMPLETED',
    amount: { value: '50.00', currency_code: 'USD' },
  });

  vi.spyOn(ordersManager, 'voidAuthorization').mockResolvedValue(true);
  vi.spyOn(ordersManager, 'refundCapture').mockResolvedValue({
    refundId: 'REF_API_789',
    status: 'COMPLETED',
    amount: { value: '50.00', currency_code: 'USD' },
  });

  vi.spyOn(payoutsManager, 'executeMilestonePayout').mockResolvedValue({
    payoutBatchId: 'BATCH_API_789',
    batchStatus: 'SUCCESS',
    senderBatchId: 'sender_api_123',
  });

  const contractManager = new ContractManager({
    ordersManager,
    payoutsManager,
    arbitrator,
    hmacSecret: config.AUDIT_HMAC_SECRET,
  });

  const app = buildApp({
    config,
    contractManager,
    arbitrator,
    webhookGuard,
  });

  const testContractPayload = {
    id: 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11',
    buyer: {
      id: 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a12',
      role: 'BUYER',
      name: 'Agent Buyer',
      paypalAccount: 'buyer@test.com',
    },
    totalAmountInCents: 5000, // $50.00
    currency: 'USD',
    sla: {
      slaId: 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a13',
      taskTitle: 'API Test Task',
      taskDescription: 'Generate test output',
      maxDeliverySeconds: 3600,
      maxArbitrationRetries: 1,
      minOverallScore: 70,
      partialReleaseThreshold: 60,
      deterministicChecks: [],
      semanticRubrics: [],
    },
    milestones: [
      {
        sequence: 1,
        name: 'Milestone 1',
        amountInCents: 5000,
        currency: 'USD',
        status: 'PENDING',
      },
    ],
    createdAt: new Date().toISOString(),
    expiresAt: new Date(Date.now() + 86400000).toISOString(),
    metadata: {},
  };

  it('responds to health, info, and arbitrator public key endpoints without auth', async () => {
    const health = await app.inject({ method: 'GET', url: '/health' });
    expect(health.statusCode).toBe(200);
    expect(JSON.parse(health.body).status).toBe('UP');

    const info = await app.inject({ method: 'GET', url: '/api/v1/info' });
    expect(info.statusCode).toBe(200);
    expect(JSON.parse(info.body).protocol).toBe('SynapsePay');

    const pubKey = await app.inject({ method: 'GET', url: '/api/v1/arbitrator/public-key' });
    expect(pubKey.statusCode).toBe(200);
    const pubKeyBody = JSON.parse(pubKey.body);
    expect(pubKeyBody.algorithm).toBe('Ed25519');
    expect(pubKeyBody.publicKey).toBeDefined();
    expect(pubKeyBody.fingerprint).toBeDefined();
  });

  it('rejects protected routes when API key is missing or wrong', async () => {
    const unauth = await app.inject({
      method: 'POST',
      url: '/api/v1/contracts',
      payload: testContractPayload,
    });
    expect(unauth.statusCode).toBe(401);

    const badKey = await app.inject({
      method: 'POST',
      url: '/api/v1/contracts',
      headers: { 'x-api-key': 'wrong_key' },
      payload: testContractPayload,
    });
    expect(badKey.statusCode).toBe(401);
  });

  it('UI Smoke Test: successfully deploys contract using exact Console UI payload (P0 Fix 7)', async () => {
    // Exact payload generated by console.html handleDeployContract
    const consolePayload = {
      id: 'f0eebc99-9c0b-4ef8-bb6d-6bb9bd380f99',
      buyer: {
        id: 'f1eebc99-9c0b-4ef8-bb6d-6bb9bd380f01',
        role: 'BUYER',
        name: 'Enterprise Agent Operator',
        paypalAccount: 'buyer@sandbox.paypal.com',
      },
      totalAmountInCents: 5000,
      currency: 'USD',
      sla: {
        slaId: 'f2eebc99-9c0b-4ef8-bb6d-6bb9bd380f02',
        taskTitle: 'Console UI Generated Task',
        taskDescription: 'Automated contract deployed from web console',
        maxDeliverySeconds: 86400,
        maxArbitrationRetries: 2,
        minOverallScore: 80,
        partialReleaseThreshold: 60,
        deterministicChecks: [
          {
            id: 'chk_det',
            name: 'Code Export Signature Assertion',
            type: 'REGEX_MATCH',
            targetField: 'module.ts',
            expectedValue: 'export function',
            weight: 2,
            required: true,
          },
        ],
        semanticRubrics: [],
      },
      milestones: [
        {
          sequence: 1,
          name: 'Final Settlement',
          amountInCents: 5000,
          currency: 'USD',
          status: 'PENDING',
        },
      ],
      createdAt: new Date().toISOString(),
      expiresAt: new Date(Date.now() + 86400000).toISOString(),
      metadata: {},
    };

    const res = await app.inject({
      method: 'POST',
      url: '/api/v1/contracts',
      headers: { 'x-api-key': config.API_KEY },
      payload: consolePayload,
    });

    expect(res.statusCode).toBe(201);
    const body = JSON.parse(res.body);
    expect(body.contract.id).toBe(consolePayload.id);
    expect(body.escrow.totalAmountInCents).toBe(5000);
  });

  it('creates contract, locks escrow, accepts, submits, and retrieves status via REST', async () => {
    // 1. Create Contract
    const createRes = await app.inject({
      method: 'POST',
      url: '/api/v1/contracts',
      headers: { 'x-api-key': config.API_KEY },
      payload: testContractPayload,
    });

    expect(createRes.statusCode).toBe(201);
    const body = JSON.parse(createRes.body);
    expect(body.contract.id).toBe(testContractPayload.id);
    expect(body.escrow.state).toBe('ESCROW_PENDING');

    // 2. Lock escrow manually
    contractManager.confirmEscrowLock(testContractPayload.id, 'AUTH_API_123');

    // 3. Worker accepts
    const workerId = 'b0eebc99-9c0b-4ef8-bb6d-6bb9bd380b22';
    const acceptRes = await app.inject({
      method: 'POST',
      url: `/api/v1/contracts/${testContractPayload.id}/accept`,
      headers: {
        'x-api-key': config.API_KEY,
        'x-agent-id': workerId,
      },
      payload: {
        id: workerId,
        role: 'WORKER',
        name: 'WorkerBot',
        paypalAccount: 'workerbot@test.com',
      },
    });
    expect(acceptRes.statusCode).toBe(200);

    // 4. Worker submits deliverable -> enters PAYOUT_PENDING
    const submitRes = await app.inject({
      method: 'POST',
      url: `/api/v1/contracts/${testContractPayload.id}/submit`,
      headers: {
        'x-api-key': config.API_KEY,
        'x-agent-id': workerId,
      },
      payload: {
        contractId: testContractPayload.id,
        workerId: workerId,
        milestoneSequence: 1,
        submittedAt: new Date().toISOString(),
        artifacts: [
          {
            name: 'main.py',
            type: 'CODE',
            content: 'print("hello synapse")',
            metadata: {},
          },
        ],
      },
    });
    expect(submitRes.statusCode).toBe(200);
    const submitBody = JSON.parse(submitRes.body);
    expect(submitBody.verdict.decision).toBe('RELEASE');
    // P0 Fix 5: State is PAYOUT_PENDING until PayPal webhook confirmation
    expect(submitBody.escrow.state).toBe('PAYOUT_PENDING');

    // 5. Confirm payout batch via webhook handler
    contractManager.confirmPayoutItemSuccess('BATCH_API_789');

    // 6. Query contract state -> now SETTLED
    const getRes = await app.inject({
      method: 'GET',
      url: `/api/v1/contracts/${testContractPayload.id}`,
      headers: { 'x-api-key': config.API_KEY },
    });

    expect(getRes.statusCode).toBe(200);
    const getBody = JSON.parse(getRes.body);
    expect(getBody.escrow.state).toBe('SETTLED');
    expect(getBody.auditIntegrity.valid).toBe(true);
  });

  it('rejects impostor agent from submitting work (P1 Fix 8)', async () => {
    const impostorContractId = 'd0eebc99-9c0b-4ef8-bb6d-6bb9bd380d11';
    await app.inject({
      method: 'POST',
      url: '/api/v1/contracts',
      headers: { 'x-api-key': config.API_KEY },
      payload: { ...testContractPayload, id: impostorContractId },
    });

    contractManager.confirmEscrowLock(impostorContractId, 'AUTH_IMP_123');

    const realWorkerId = 'b0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11';
    await app.inject({
      method: 'POST',
      url: `/api/v1/contracts/${impostorContractId}/accept`,
      headers: { 'x-api-key': config.API_KEY, 'x-agent-id': realWorkerId },
      payload: {
        id: realWorkerId,
        role: 'WORKER',
        name: 'RealWorker',
        paypalAccount: 'real@worker.io',
      },
    });

    // Impostor attempts to submit
    const impostorAgentId = 'c0eebc99-9c0b-4ef8-bb6d-6bb9bd380b22';
    const impostorRes = await app.inject({
      method: 'POST',
      url: `/api/v1/contracts/${impostorContractId}/submit`,
      headers: {
        'x-api-key': 'agent_impostor_secret_key_16_chars',
        'x-agent-id': impostorAgentId,
      },
      payload: {
        contractId: impostorContractId,
        workerId: realWorkerId, // Trying to submit as real worker
        milestoneSequence: 1,
        artifacts: [{ name: 'hack.ts', type: 'CODE', content: 'fake code', metadata: {} }],
      },
    });

    // Must be rejected with 403 Forbidden!
    expect(impostorRes.statusCode).toBe(403);
  });

  it('blocks non-admin agent from triggering admin kill-switch (P1 Fix 8)', async () => {
    const res = await app.inject({
      method: 'POST',
      url: '/api/v1/admin/kill-switch',
      headers: { 'x-api-key': 'agent_standard_worker_key_16_chars' },
      payload: { active: true },
    });
    expect(res.statusCode).toBe(403);
  });

  it('handles contract negotiation via REST endpoints (P1 Fix 14)', async () => {
    const negContractId = 'e0eebc99-9c0b-4ef8-bb6d-6bb9bd380e22';
    await app.inject({
      method: 'POST',
      url: '/api/v1/contracts',
      headers: { 'x-api-key': config.API_KEY },
      payload: { ...testContractPayload, id: negContractId },
    });

    // Propose counter terms
    const proposeRes = await app.inject({
      method: 'POST',
      url: `/api/v1/contracts/${negContractId}/negotiate`,
      headers: { 'x-api-key': config.API_KEY },
      payload: {
        proposedBy: 'WORKER',
        proposedAmountInCents: 8000,
        proposedDeliverySeconds: 7200,
        notes: 'Extended scope request',
      },
    });
    expect(proposeRes.statusCode).toBe(201);
    const proposal = JSON.parse(proposeRes.body);

    // List proposals
    const listRes = await app.inject({
      method: 'GET',
      url: `/api/v1/contracts/${negContractId}/proposals`,
      headers: { 'x-api-key': config.API_KEY },
    });
    expect(listRes.statusCode).toBe(200);
    expect(JSON.parse(listRes.body).length).toBe(1);

    // Accept proposal
    const acceptRes = await app.inject({
      method: 'POST',
      url: `/api/v1/contracts/${negContractId}/negotiate/${proposal.id}/accept`,
      headers: { 'x-api-key': config.API_KEY },
    });
    expect(acceptRes.statusCode).toBe(200);
    expect(JSON.parse(acceptRes.body).contract.totalAmountInCents).toBe(8000);
  });

  it('processes incoming PayPal webhooks and rejects duplicates (P0 Fix 6)', async () => {
    const webhookPayload = {
      id: 'WH-EVT-DEDUP-999',
      create_time: new Date().toISOString(),
      resource_type: 'authorization',
      event_type: 'PAYMENT.AUTHORIZATION.CREATED',
      resource: {
        id: 'AUTH_WH_999',
        custom_id: testContractPayload.id,
      },
    };

    const webhookHeaders = {
      'paypal-auth-algo': 'SHA256withRSA',
      'paypal-cert-url': 'https://api.sandbox.paypal.com/v1/notifications/certs/CERT-123',
      'paypal-transmission-id': 'trans_wh_1',
      'paypal-transmission-sig': 'sig_wh_1',
      'paypal-transmission-time': new Date().toISOString(),
    };

    // First delivery -> ACKNOWLEDGED
    const res1 = await app.inject({
      method: 'POST',
      url: '/api/v1/webhooks/paypal',
      headers: webhookHeaders,
      payload: webhookPayload,
    });
    expect(res1.statusCode).toBe(200);
    expect(JSON.parse(res1.body).status).toBe('ACKNOWLEDGED');

    // Duplicate delivery -> DUPLICATE_ACKNOWLEDGED
    const res2 = await app.inject({
      method: 'POST',
      url: '/api/v1/webhooks/paypal',
      headers: webhookHeaders,
      payload: webhookPayload,
    });
    expect(res2.statusCode).toBe(200);
    expect(JSON.parse(res2.body).status).toBe('DUPLICATE_ACKNOWLEDGED');
  });

  it('exposes public reputation and audit checkpoint endpoints (P2 Differentiators)', async () => {
    const repRes = await app.inject({
      method: 'GET',
      url: '/api/v1/agents/sample-worker-id/reputation',
    });
    expect(repRes.statusCode).toBe(200);
    const repBody = JSON.parse(repRes.body);
    expect(repBody).toHaveProperty('reputationScore');
    expect(repBody).toHaveProperty('attestationSignature');

    const cpRes = await app.inject({
      method: 'GET',
      url: `/api/v1/contracts/${testContractPayload.id}/checkpoint`,
      headers: { 'x-api-key': config.API_KEY },
    });
    expect(cpRes.statusCode).toBe(200);
    const cpBody = JSON.parse(cpRes.body);
    expect(cpBody).toHaveProperty('rootHash');
    expect(cpBody).toHaveProperty('signature');
  });

  it('cryptographically verifies authentic verdicts and rejects forged verdicts via /api/v1/arbitrator/verify', async () => {
    // 1. Rejects forged verdict with fake signature
    const fakeVerdict = {
      contractId: '00000000-0000-0000-0000-000000000000',
      milestoneSequence: 1,
      decision: 'RELEASE',
      overallScore: 100,
      payoutPercentage: 1.0,
      canRetry: false,
      evaluatedAt: new Date().toISOString(),
      deterministicResults: [],
      semanticResults: [],
      rationale: 'Attacker forged verdict',
      arbitratorPublicKey: 'deadbeef',
      signedVerdictSignature: '00',
    };

    const forgedRes = await app.inject({
      method: 'POST',
      url: '/api/v1/arbitrator/verify',
      payload: { verdict: fakeVerdict },
    });
    expect(forgedRes.statusCode).toBe(200);
    const forgedBody = JSON.parse(forgedRes.body);
    expect(forgedBody.valid).toBe(false);
    expect(forgedBody.reason).toContain('Cryptographic signature mismatch');

    // 2. Accepts authentic verdict signed by server arbitrator
    const seededContracts = contractManager.listContracts();
    const settledContract = seededContracts.find((c) => c.verdict && c.verdict.signedVerdictSignature);
    if (settledContract && settledContract.verdict) {
      const validRes = await app.inject({
        method: 'POST',
        url: '/api/v1/arbitrator/verify',
        payload: { verdict: settledContract.verdict },
      });
      expect(validRes.statusCode).toBe(200);
      const validBody = JSON.parse(validRes.body);
      expect(validBody.valid).toBe(true);
      expect(validBody.algorithm).toBe('Ed25519');
      expect(validBody.reason).toContain('verified successfully');
    }
  });
});
